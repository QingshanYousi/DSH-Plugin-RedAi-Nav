/**
 * Assembles lib/client.js from src/*.js.
 *
 * The fragments are concatenated inside one module-factory closure — not
 * bundled: nothing is transpiled, minified or renamed, so the file the browser
 * executes is the file a reviewer can read. Keeping the build this small is the
 * whole point: a third-party bundler would break the `factory(require)` contract
 * and the "zero dependencies" claim the disclosure makes.
 *
 *   node scripts/build.mjs          # write lib/client.js
 *   node scripts/build.mjs --check  # fail when the artifact is stale (CI)
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))

// Declaration order is dependency order: data first, exports last.
const PARTS = ['data', 'store', 'components', 'plugins', 'page']

const HEADER = [
  '/**',
  ' * ' + pkg.name + ' — browser half of the plugin.',
  ' *',
  ' * GENERATED by scripts/build.mjs from src/{' + PARTS.join(',') + '}.js.',
  ' * Do not edit this file: edit the sources, then run `npm run build`.',
  ' *',
  ' * Registers two things against the shipped client slots:',
  ' *   - `sidebar.panellist` — the nav row; the shell renders the row itself',
  ' *     (height, hover, collapsed rail, tooltip, aria-current), so this plugin',
  ' *     supplies only an icon component and a locale-aware label.',
  ' *   - `main` — the keyed page the row selects. The key must equal the row id.',
  ' *',
  ' * No bundler is involved: the fragments share one scope inside the module',
  ' * envelope the client module system expects, and `react` resolves from the',
  ' * shell baseline module table. User data (custom sites, stars, recents) lives',
  ' * in localStorage only — no fetch, no XMLHttpRequest, no third-party service.',
  ' */',
].join('\n')

const indent = (text) => text
  .replace(/\r\n/g, '\n')
  .replace(/\s+$/g, '')
  .split('\n')
  .map((line) => (line.length > 0 ? '    ' + line : ''))
  .join('\n')

const fragments = PARTS.map((name) => {
  const file = join(root, 'src', name + '.js')
  if (!existsSync(file)) throw new Error('missing fragment: src/' + name + '.js')
  const body = readFileSync(file, 'utf8')
  if (/^\s*(import|export)\s/m.test(body)) {
    throw new Error('src/' + name + '.js must not use import/export — fragments share one scope')
  }
  return '    // ── src/' + name + '.js ──\n' + indent(body)
})

const artifact = [
  HEADER,
  'window.__ModuleLoader__.load({',
  // The id must equal the package name: the client module graph keys on it.
  "  id: '" + pkg.name + "',",
  '  factory: (require) => {',
  '    var module = { exports: {} }',
  '    var exports = module.exports',
  "    Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' })",
  '',
  "    const React = require('react')",
  "    const jsxRuntime = require('react/jsx-runtime')",
  '    const jsx = jsxRuntime.jsx',
  '    const jsxs = jsxRuntime.jsxs',
  '',
  fragments.join('\n\n'),
  '',
  '    return module.exports',
  '  },',
  '})',
  '',
].join('\n')

const target = join(root, 'lib/client.js')
const current = existsSync(target) ? readFileSync(target, 'utf8') : null

if (process.argv.includes('--check')) {
  if (current !== artifact) {
    console.error('lib/client.js is stale — run `npm run build` and commit the result')
    process.exit(1)
  }
  console.log('lib/client.js matches src/ (%d lines)', artifact.split('\n').length - 1)
} else {
  writeFileSync(target, artifact)
  console.log('assembled lib/client.js from %d fragments (%d lines)',
    fragments.length, artifact.split('\n').length - 1)
}

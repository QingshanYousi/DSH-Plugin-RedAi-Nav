/**
 * Embeds the data files into a generated source fragment and mirrors the
 * dictionaries into locale/*.json for tools that read them.
 *
 * `src/data.js` is generated, never hand-edited: `links.json` and `i18n.json`
 * stay the single source of truth, and scripts/build.mjs concatenates the
 * fragment into lib/client.js (a single file cannot import JSON at runtime).
 *
 *   node scripts/embed-data.mjs          # write
 *   node scripts/embed-data.mjs --check  # fail when stale (CI)
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'))

const links = read('data/links.json')
const i18n = read('data/i18n.json')
const details = read('data/details.json')
const plugins = read('data/plugins.json')

if (links.version !== 1) throw new Error(`unsupported links schema version: ${links.version}`)
if (i18n.version !== 1) throw new Error(`unsupported i18n schema version: ${i18n.version}`)
if (details.version !== 1) throw new Error(`unsupported details schema version: ${details.version}`)
if (plugins.version !== 2) throw new Error(`unsupported plugins schema version: ${plugins.version}`)

for (const url of Object.keys(details.sites)) {
  if (!/^https?:\/\//.test(url)) throw new Error(`details key must be a URL: ${url}`)
}

const targetPath = join(root, 'src/data.js')
const current = existsSync(targetPath) ? readFileSync(targetPath, 'utf8') : ''

const block = [
  '/**',
  ' * GENERATED by scripts/embed-data.mjs — edit data/*.json, then run `npm run data`.',
  ' *',
  ' * Read-only snapshot of the data files: links, editorial detail pages, the',
  ' * plugin ranking and the dictionaries. Do not edit by hand; the build script',
  ' * concatenates this fragment into lib/client.js.',
  ' */',
  '',
  `const LINKS = ${JSON.stringify(links)}`,
  '',
  `const DETAILS = ${JSON.stringify(details.sites)}`,
  '',
  `const PLUGINS = ${JSON.stringify(plugins)}`,
  '',
  `const I18N = ${JSON.stringify(i18n.locales)}`,
  '',
].join('\n')

// locale/*.json mirrors of the same dictionaries, one file per locale.
for (const [locale, dict] of Object.entries(i18n.locales)) {
  mkdirSync(join(root, 'locale'), { recursive: true })
  writeFileSync(join(root, 'locale', `${locale}.json`), JSON.stringify(dict, null, 2) + '\n')
}

const check = process.argv.includes('--check')
if (check) {
  if (block !== current) {
    console.error('src/data.js is stale — run `npm run data` and commit the result')
    process.exit(1)
  }
  console.log('embedded data is up to date (%d groups, %d links)', links.groups.length,
    links.groups.reduce((n, g) => n + g.links.length, 0))
} else {
  writeFileSync(targetPath, block)
  console.log('embedded %d groups / %d links into src/data.js',
    links.groups.length, links.groups.reduce((n, g) => n + g.links.length, 0))
}
